import assert from 'node:assert/strict';
import {getAccessChoices,preferredSingleChoice} from '../access-router.js';
const admin=[{org_id:'org-one',member_role:'admin'}];
const student=[{org_id:'org-one',member_role:'student'}];
const parent=[{view_role:'parent',student_name:'Example Student'}];
const tutor=[{view_role:'tutor',student_name:'Example Student'}];
const kinds=items=>items.map(x=>x.kind);
assert.deepEqual(kinds(getAccessChoices(admin,[])),['studio'],'Admin must open Studio');
assert.deepEqual(kinds(getAccessChoices([{member_role:'partner'}],[])),['studio'],'Partner must open Studio');
assert.deepEqual(kinds(getAccessChoices([{member_role:'examiner'}],[])),['studio'],'Examiner must open Studio');
assert.deepEqual(kinds(getAccessChoices(student,[])),['student'],'Student must open learning space');
assert.deepEqual(kinds(getAccessChoices([],parent)),['family'],'Verified guardian view must open family dashboard');
assert.deepEqual(kinds(getAccessChoices([],tutor)),['family'],'Verified tutor view must open family dashboard');
assert.match(getAccessChoices([],parent)[0].label,/Parent/,'Parent label');
assert.match(getAccessChoices([],tutor)[0].label,/Tutor/,'Tutor label');
assert.deepEqual(kinds(getAccessChoices([],[...parent,...tutor])),['family'],'Parent and tutor may share an entry point with view selector');
assert.deepEqual(kinds(getAccessChoices(admin,parent)),['studio','family'],'Dual admin/parent must be offered both roles');
assert.deepEqual(kinds(getAccessChoices(student,tutor)),['student','family'],'Dual student/tutor must be offered both roles');
assert.deepEqual(kinds(getAccessChoices([...admin,...student],[])),['studio','student'],'Dual staff/student must be offered both roles');
assert.equal(preferredSingleChoice(getAccessChoices(admin,[]))?.kind,'studio');
assert.equal(preferredSingleChoice(getAccessChoices([],parent))?.kind,'family');
assert.equal(preferredSingleChoice(getAccessChoices(admin,parent)),null,'Do not choose silently when two roles are authorised');
assert.deepEqual(getAccessChoices([],[]),[],'An uninvited verified email must not be assigned a dashboard');
assert.deepEqual(kinds(getAccessChoices([],[],1)),['family'],'Pending viewer invitation may open pending view, not student or admin');
assert.deepEqual(getAccessChoices([{member_role:'hacker'}],[]),[],'Unknown database roles must not grant access');
assert.equal(getAccessChoices([{member_role:'examiner'},{member_role:'admin'}],[])[0].label,'Administrator Studio','Admin takes precedence for staff.');
console.log('Unified email sign-in routing: 19 role scenarios passed. Server-side permission checks still required for real accounts.');
