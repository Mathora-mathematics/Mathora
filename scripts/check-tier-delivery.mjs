import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(p,'utf8');
const cal=read('supabase/migrations/20261102_calendar_explain_tier_question_supply.sql');
const assign=read('supabase/migrations/20261102_adaptive_mixed_topic_assignment.sql');
const mock=read('supabase/migrations/20261102_live_monthly_practice_mock.sql');
const aliases=read('supabase/migrations/20261102_igcse_pearson_tier_aliases.sql');
const inherited=read('supabase/migrations/20261102_subscription_weekly_inheritance.sql');
const noRepeat=read('supabase/migrations/20261031_unseen_question_text_guard.sql');
const practice=read('assigned-practice.js');
const staff=read('assigned-admin.js');
const tiers=JSON.parse(read('content/programmes/service-tiers.json')).plans;
assert.deepEqual(Object.keys(tiers).sort(),['daily','exam','weekly']);
assert.match(cal,/unseen_questions/,'Student calendar must publish truthful unseen supply count');
assert.match(cal,/status<>'scheduled' OR programme=v_tier/,'Stale scheduled items from an old tier must be hidden');
assert.match(practice,/schedule\.unseen_questions/,'UI must use real available-question count');
assert.match(practice,/Preparing verified questions/,'Student must not get misleading Ready status when bank is exhausted');
assert.match(practice,/slice\(0,42\)/,'Student must be able to preview beyond the first 20 days');
assert.match(assign,/v_baseline_score/,'Difficulty must use baseline as a starting point');
assert.match(assign,/v_recent_count>=4/,'Examiner feedback must affect later assignment selection');
assert.match(assign,/PARTITION BY b.topic/,'First wave must sample different mathematical topics');
assert.match(assign,/review_state='approved'/,'Drafts and pilot questions must not be sent to students');
assert.match(assign,/grove_board_compatible/,'Assigned exam board must be verified');
assert.match(assign,/old\.bank_id=b\.id OR lower\(regexp_replace\(old\.prompt/,'Prevent same-bank and identical-text repeats');
assert.match(noRepeat,/CREATE UNIQUE INDEX/,'Active bank stems must be unique within academic routes');
assert.match(mock,/v\.mode='mock' THEN now\(\)\+interval '90 minutes'/,'Mock needs 90-minute server-side expiry');
assert.match(mock,/'mock',v_date,20/,'Grove Exam requires a monthly 20-item timed practice assessment');
assert.match(mock,/\'mock\'::text/,'Database must admit the new monthly mock mode');
assert.match(mock,/t\.mode='mock_pending' AND t\.status='scheduled'/,'Convert only unopened legacy monthly placeholders');
assert.match(practice,/mock:'Monthly timed mock/,'Student mock must be navigable');
assert.match(staff,/mock:'20-question timed monthly mock'/,'Examiner must distinguish mock mode');
assert.match(aliases,/v_norm LIKE '%foundation%'/,'Pearson IGCSE Foundation should route to Core');
assert.match(aliases,/v_norm LIKE '%higher%'/,'Pearson IGCSE Higher should route to Extended');
assert.match(inherited,/v_prog IN \('daily','exam'\)/,'Grove Daily and Exam must inherit weekly practice sets on enrolment');
assert.match(inherited,/v_tier,'weekly',v_day,8/,'Student dashboard must schedule inherited weekly sets');
assert.match(inherited,/CASE WHEN v.mode='weekly' THEN 'weekly' ELSE v.programme END/,'A weekly set must use weekly-approved questions, not the daily/exam pool');
assert.match(inherited,/weekly_unseen_questions/,'Weekly bank supply must be separately reported');
assert.match(practice,/r.mode==='weekly'\?schedule.weekly_unseen_questions:schedule.unseen_questions/,'Frontend Ready status must use the appropriate pool per mode');
assert.ok(tiers.daily.cadence.includes('PLUS')&&tiers.exam.cadence.includes('PLUS'),'Tier catalogue must describe inheritance and monthly mock accurately');

console.log('MathsGrove tier delivery: calendar supply, no repeats, baseline adaptation, topic rotation, board aliases, 90-minute monthly mock, examiner queue — PASS');
